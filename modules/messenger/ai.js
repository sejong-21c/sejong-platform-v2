// "올해"·"작년"·"2025년" 을 연도로. 없으면 null(전체를 센다).
function 연도뽑기(질문) {
  const m = String(질문 || '').match(/(20\d{2})\s*년?/);
  if (m) return m[1];
  const 올 = new Date().getFullYear();
  if (/올해|금년|이번\s*해|올 해/.test(질문)) return String(올);
  if (/작년|지난해|지난 해/.test(질문)) return String(올 - 1);
  if (/재작년/.test(질문)) return String(올 - 2);
  return null;
}

/** 질문에 나온 기록 종류를 골라 **Firestore 에서 직접 센다.** 세는 질문이 아니면 부르지 않는다. */
export async function 기록세기(질문, fb) {
  // fb 에 getCountFromServer 가 없으면 옛 껍데기를 쓰고 있는 것이다 — 조용히 건너뛴다.
  if (!fb || typeof fb.getCountFromServer !== 'function' || !fb.db) return [];
  const g = 다듬(질문);
  const 고른 = 셀것.filter((s) => s.별칭.some((a) => g.includes(다듬(a)))).slice(0, 3);
  if (!고른.length) return [];
  const 해 = 연도뽑기(질문);
  const 답 = [];
  for (const s of 고른) {
    try {
      const 밑 = fb.collection(fb.db, s.컬렉션);
      // 날짜는 전부 'YYYY-MM-DD' 문자열이라 한 필드 범위로 끝난다 — 복합 색인이 필요 없다.
      const q = (해 && s.날짜)
        ? fb.query(밑, fb.where(s.날짜, '>=', 해 + '-01-01'), fb.where(s.날짜, '<=', 해 + '-12-31'))
        : fb.query(밑);
      const r = await fb.getCountFromServer(q);
      답.push({ 이름: s.이름, 수: r.data().count, 해: (해 && s.날짜) ? 해 : null });
    } catch (e) {
      // 권한이 없거나 컬렉션이 없다. **말없이 빼지 않는다** — 안 센 걸 사람이 알아야 한다.
      답.push({ 이름: s.이름, 오류: String(e && e.message || e).slice(0, 80) });
    }
  }
  return 답;
}

// ── 답에 나온 화면 이름 고르기 ─────────────────────────────────────────────
// 왜 이게 필요한가: 모델은 화면 이름만 알고 **버튼·차례는 모른다.** 그런데 "어떻게 하나요" 를
//   물으면 아는 척 지어낸다("업무 등록 버튼 선택"). 프롬프트로 네 번(b69~b72) 막아 봤지만 졌다.
//   그래서 부탁을 그만두고 구조를 바꾼다 — 모델은 **이름만** 내고, 누를 것은 우리가 그린다.
// 이름은 부모 앱에서 온 진짜 목록이라 지어낼 자리가 없다.
// 공백·가운뎃점·괄호·따옴표를 다 버리고 글자만 남긴다(역슬래시 없는 규칙 — 한 번 깨져 봤다)
const 다듬 = (s) => String(s || '').toLowerCase().replace(/[^0-9a-z가-힣]/g, '');
// ── 가는 길 설명 지우기 ────────────────────────────────────────────────────
// 버튼을 붙였으면 "왼쪽 메뉴 업무관리 클릭 · '업무 등록' 버튼 선택" 같은 줄은 지운다.
//   거기에 **없는 버튼 이름**이 들어 있고, 이제 진짜 버튼이 바로 밑에 있어 쓸모도 없다.
//   b69~b72 네 번 부탁해 봤지만 모델은 계속 썼다. 부탁 대신 지운다.
// 안전장치 둘: (1) 버튼이 있을 때만 (2) 지운 뒤 글이 너무 짧아지면 원래대로 되돌린다.
//   "제목·날짜·금액 입력" 처럼 **무엇을 준비하라**는 줄은 메뉴·버튼 말이 없으니 남는다.
const 길설명 = /왼쪽\s*메뉴|클릭|버튼\s*(을\s*)?(선택|누르)|화면으로\s*이동|메뉴에서\s*선택/;
export function 길설명빼기(글, 버튼있나) {
  const 원래 = String(글 || '');
  if (!버튼있나 || !원래.trim()) return 원래;
  const 남은 = 원래.split('\n').filter((l) => !길설명.test(l)).join('\n').replace(/\n{3,}/g, '\n\n').trim();
  if (남은.length < 30 || 남은.length < 원래.trim().length * 0.4) return 원래;   // 너무 깎였으면 손대지 않는다
  return 남은;
}

// ── 고치기 제안 뽑기 (2026-09-23) ─────────────────────────────────────────
// 모델이 답 끝에 붙인 ```실행 { … } ``` 덩이를 **글에서 떼어내** 따로 돌려준다.
//   떼어내는 이유: 말풍선에 JSON 이 그대로 보이면 사람이 읽을 게 못 된다. 확인 카드로 그린다.
// 여기서 하는 검사는 **꼴 검사뿐**이다 — 대상이 실재하는지, 권한이 있는지, 무엇이 바뀌는지는
//   전부 부모 앱(window.AI행위풀기)이 실제 자료를 보고 정한다. 모델 말을 믿고 쓰지 않는다.
export function 실행뽑기(글, 할수있는행위 = null) {
  const s = String(글 || '');
  // ```실행 … ``` 또는 ```json … ``` 어느 쪽으로 싸도 받는다(모델이 종종 json 으로 쓴다).
  const m = s.match(/```(?:실행|json)?\s*(\{[\s\S]*?\})\s*```/);
  if (!m) return { 글: s, 제안: null };
  const 남은 = s.replace(m[0], '').trim();
  let o = null;
  try { o = JSON.parse(m[1]); } catch (e) { return { 글: 남은, 제안: null }; }
  if (!o || typeof o !== 'object' || Array.isArray(o)) return { 글: 남은, 제안: null };

  const 행위 = String(o.행위 || '').trim();
  if (!행위) return { 글: 남은, 제안: null };
  // 할 수 있는 것만 받는다. 없는 행위로 카드를 띄우면 눌러 보고서야 안 된다는 걸 알게 된다.
  if (Array.isArray(할수있는행위) && !할수있는행위.includes(행위)) return { 글: 남은, 제안: null };

  // **값의 꼴을 여기서 거른다.** Number(null) 과 Number(false) 는 0 인데 0 은 대개 유효한
  //   값이라(진척률 0% = 미시작) 그대로 통과한다 — 모델이 칸을 못 채워 null 을 뱉으면
  //   **진척률을 0 으로 지우는** 카드가 뜬다. 시험이 이걸 잡았다(2026-09-23).
  //   그래서 글자나 수만 받고, 빈 것은 아예 뺀다. 빠진 칸은 각 행위가 "안 준 것"으로 다룬다.
  const 인자 = {};
  for (const [k, v] of Object.entries(o)) {
    if (k === '행위' || k === '도구') continue;
    if (typeof v === 'number') { if (Number.isFinite(v)) 인자[k] = v; continue; }
    if (typeof v === 'string') { const t = v.trim(); if (t) 인자[k] = t; continue; }
    // null · true/false · 배열 · 객체는 버린다.
  }
  if (!Object.keys(인자).length) return { 글: 남은, 제안: null };
  return { 글: 남은, 제안: { 행위, 인자 } };
}

export function 화면고르기(글, 목록) {
  const g = 다듬(글);
  if (!g || !Array.isArray(목록) || !목록.length) return [];
  const 맞은 = [];
  for (const s of 목록) {
    const n = 다듬(s.이름);
    if (n.length < 2) continue;              // 한 글자 이름은 아무 글에나 걸린다
    const 자리 = g.indexOf(n);
    if (자리 >= 0) 맞은.push({ ...s, 자리 });
  }
  맞은.sort((x, y) => x.자리 - y.자리 || 다듬(y.이름).length - 다듬(x.이름).length);
  const 고른 = [];
  for (const m of 맞은) {
    // 겹치는 이름은 하나만 — "QA Doc 조회" 가 잡혔으면 그 안에 든 짧은 이름은 버린다
    const 나 = 다듬(m.이름);
    if (고른.some((x) => { const t = 다듬(x.이름); return t.includes(나) || 나.includes(t); })) continue;
    고른.push(m);
    if (고른.length >= 2) break;             // 버튼 셋이 붙으면 답보다 버튼이 커진다
  }
  return 고른.map(({ 종류, id, 이름, 부서 }) => ({ 종류, id, 이름, ...(부서 ? { 부서 } : {}) }));
}

