const 큰한도 = 12000;
export const 고정한도 = 3600;          // 안내문(맥락 빼고)이 이보다 크면 맥락·앞말 자리가 2,000 토큰도 안 남는다 — 시험이 막는다

// ── 맥락 조각 ────────────────────────────────────────────────────────────────
// 9/25 첫 판은 맥락 **뒤**부터 잘랐다. 검토에서 잡혔다: 맥락은 직원·프로젝트·업무 목록 **다음에** 문서 조각이 온다 —
//   문서 질문인데 문서가 통째로 잘리고, 출처 칩은 모델이 못 본 문서를 근거로 보여 줬다.
//   그래서 조각마다 **급**을 매긴다. 낮은 급부터 통째로 뺀다(같은 급이면 뒤에 넣은 것부터 — 문서는 점수 순이라 낮은 것부터).
//   급은 질문 갈래로 바뀐다: 찾기면 문서가 목록보다 높고, 세는 질문이면 센 수·표가 제일 높고 문서가 제일 낮다.
// 앞 대화도 같은 저울에 오른다: **바로 앞 주고받음**(끝 둘)은 통째로 문서보다 위 — "셋째 문단만 고쳐줘" 는 앞 답 전문이 있어야 한다.
//   그보다 오래된 말은 머리(600자)가 목록 사이, 나머지가 목록 아래.
export const 급 = { 안뺌: 100, 짚은것: 90, 센수: 95, 표머리: 95, 표줄: 80, 마지막말: 65, 마지막말꼬리: 62, 문서찾기: 60, 업무: 45, 옛말머리: 40, 프로젝트: 35, 직원: 30, 옛말꼬리: 25, 문서세기: 20 };

/** 급 낮은 것부터 빼서 남길토큰 안으로, 그다음 **빈자리에 급 높은 것부터 다시 채운다**.
 *  같은 급이면 순(없으면 넣은 차례)이 큰 것부터 뺀다 — 문서는 점수 순이라 뒤(낮은 점수)부터, 앞말은 오래된 것부터.
 *  무리: 몸이 다 빠지면 머리도 빠진다(머리남김이면 남긴다). 일부라도 빠지면 잘림말을 붙이고 그 몫도 센다.
 *  9/25 두 번째 검토: 한 번 훑고 끝내면 큰 조각 하나가 빠진 뒤 남은 자리가 그냥 논다(맥락이 텅 비었다).
 *  ponytail: 욕심 알고리즘이다(최적 배낭 아님). 조각이 수백 개라 이걸로 충분하다. */
function 빼기(조각들, 남길토큰) {
  const 것 = (조각들 || []).map((c, i) => ({ ...c, i, 순: c.순 ?? i, 토큰: 추정토큰(c.글) + 1, 빠짐: false }));
  const 무리머리 = new Map(), 무리몸 = new Map(), 잘림말토큰 = new Map();
  for (const c of 것) {
    if (!c.무리) continue;
    (c.머리 ? 무리머리 : 무리몸).set(c.무리, [...((c.머리 ? 무리머리 : 무리몸).get(c.무리) || []), c]);
    if (c.잘림말) 잘림말토큰.set(c.무리, 추정토큰(c.잘림말) + 1);
  }
  const 머리남김 = (g) => (무리머리.get(g) || []).some((c) => c.머리남김);
  // 지금 보낼 글의 크기 — 조각 + 무리마다 (일부 빠졌으면) 잘림말. 머리는 몸이 하나도 없으면 안 센다(머리남김 빼고).
  const 잰다 = () => {
    let 합 = 0;
    for (const c of 것) if (!c.빠짐 && !c.머리) 합 += c.토큰;
    for (const [g, 머리들] of 무리머리) {
      const 몸 = 무리몸.get(g) || [];
      const 산몸 = 몸.filter((c) => !c.빠짐).length;
      if (산몸 || 머리남김(g) || !몸.length) 합 += 머리들.reduce((a, c) => a + c.토큰, 0);
    }
    for (const [g, 몸] of 무리몸) if (몸.some((c) => c.빠짐) && (몸.some((c) => !c.빠짐) || 머리남김(g))) 합 += 잘림말토큰.get(g) || 0;
    for (const c of 것) if (!c.빠짐 && c.덧붙임) 합 += c.덧붙임;
    return 합;
  };
  const 뺄것 = 것.filter((c) => !c.머리 && (c.급 ?? 50) < 급.안뺌).sort((a, b) => (a.급 ?? 50) - (b.급 ?? 50) || b.순 - a.순);
  let 합 = 잰다();
  for (const c of 뺄것) { if (합 <= 남길토큰) break; c.빠짐 = true; 합 = 잰다(); }
  // 다시 채우기 — 급 높은 것부터(같으면 먼저 빠질 뻔한 쪽이 나중)
  for (const c of [...뺄것].reverse()) {
    if (!c.빠짐) continue;
    c.빠짐 = false;
    const 새합 = 잰다();
    if (새합 <= 남길토큰) 합 = 새합; else c.빠짐 = true;
  }
  const 잘린무리 = new Set();
  for (const [g, 몸] of 무리몸) {
    if (몸.every((c) => c.빠짐) && !머리남김(g)) (무리머리.get(g) || []).forEach((c) => { c.빠짐 = true; });
    if (몸.some((c) => c.빠짐) && (몸.some((c) => !c.빠짐) || 머리남김(g))) 잘린무리.add(g);
  }
  return { 것, 잘린무리, 합 };
}
function 글로(것, 잘린무리) {
  const 줄 = [];
  const 붙인 = new Set();
  것.forEach((c, k) => {
    if (c.빠짐) return;
    줄.push(c.글);
    if (!c.무리 || !잘린무리.has(c.무리) || 붙인.has(c.무리)) return;
    const 다음남은 = 것.slice(k + 1).some((x) => x.무리 === c.무리 && !x.빠짐);   // 무리의 마지막 남은 조각 뒤에 잘림말
    if (!다음남은) { const 말 = 것.find((x) => x.무리 === c.무리 && x.잘림말); if (말) { 줄.push(말.잘림말); 붙인.add(c.무리); } }
  });
  return 줄.join('\n');
}

/** 조각 = { 글, 급, 순?, 무리?, 머리?, 머리남김?, 문서?, 조각?, 잘림말? }. 순수 함수 — 시험이 이 규칙을 못 박는다.
 *  돌려주는 것: { 글, 남은문서(이름), 남은조각(조각 id — 그림은 이걸로 고른다), 뺀수 }. */
export function 맥락맞추기(조각들, 남길토큰) {
  const { 것, 잘린무리 } = 빼기(조각들, 남길토큰);
  const 산 = 것.filter((c) => !c.빠짐);
  return { 글: 글로(것, 잘린무리), 남은문서: [...new Set(산.filter((c) => c.문서).map((c) => c.문서))], 남은조각: 산.filter((c) => c.조각 != null).map((c) => c.조각), 뺀수: 것.length - 산.length };
}

/** 예전처럼 맥락이 글 하나로 오면 줄마다 조각으로 — 뒤부터 빠진다. */
const 글을조각으로 = (글) => String(글 || '').split('\n').map((줄) => ({ 글: 줄, 급: 50 }));

/** 보내기 전에 잰다. 넘치면 맥락 조각과 앞 대화를 **한 저울**에서 급 낮은 것부터 뺀다(그리고 빈자리를 다시 채운다).
 *  앞 대화: 끝 둘(바로 앞 주고받음)은 머리 1,500자가 문서보다 위, 그 뒤가 바로 그 아래. 그보다 오래된 말은 머리 600자·꼬리.
 *    같은 급이면 **오래된 말부터** 뺀다. 옛 답은 넘칠 때만 줄인다.
 *  질문은 **질문 하나가 정말 클 때만** 자른다 — 자른 뒤 다시 재고, 센 수·표 머리 자리는 먼저 뗀다. */
export function 크기맞추기({ 질문, 앞말, 맥락, 짓기, 한도 = 입력한도 }) {
  const 조각들 = Array.isArray(맥락) ? 맥락 : 글을조각으로(맥락);
  // 틀 몫 — 9/25 실물 두 번: 어림 4,923 → 실제 4,972 · 5,126 → 5,206 (메시지 틀이 어림보다 컸다). 80 → 180.
  const 고정 = 추정토큰(짓기('')) + 180;
  const 말 = (앞말 || []).slice(-12);
  let 물음 = String(질문 || '');
  const 말토큰 = (m) => m.reduce((a, x) => a + 추정토큰(x.text) + 4, 0);
  const 처음 = 고정 + 말토큰(말) + 추정토큰(물음) + 조각들.reduce((a, c) => a + 추정토큰(c.글) + 1, 0);
  if (처음 <= 한도) {
    const m = 맥락맞추기(조각들, Infinity);
    return { 앞말: 말, 질문: 물음, 맥락: m.글, 남은문서: m.남은문서, 남은조각: m.남은조각, 추정: 처음, 처음, 줄였나: false };
  }
  const 뒷말 = ' …(앞부분만)';
  const 말조각 = [];
  말.forEach((x, k) => {
    const t = String(x.text || '');
    const 끝쪽 = k >= 말.length - 2;
    const 머길이 = 끝쪽 ? 1500 : 600;
    const 순 = -k * 10;                          // 오래된 말(작은 k)이 같은 급에서 먼저 빠진다
    말조각.push({ 글: t.slice(0, 머길이), 급: 끝쪽 ? 급.마지막말 : 급.옛말머리, 말: k, 쪽: '머리', 순 });
    if (t.length > 머길이) 말조각.push({ 글: t.slice(머길이), 급: 끝쪽 ? 급.마지막말꼬리 : 급.옛말꼬리, 말: k, 쪽: '꼬리', 순: 순 + 1, 덧붙임: 0 });
  });
  const 풀기 = (덜기 = 0) => {
    const 남길 = 한도 - 고정 - 추정토큰(물음) - 4 * 말.length - 덜기;
    // 꼬리가 빠지면 머리에 '…(앞부분만)' 이 붙는다 — 그 몫을 머리에 미리 얹어 센다.
    const 모두 = [...조각들, ...말조각.map((c) => (c.쪽 === '머리' && 말조각.some((d) => d.말 === c.말 && d.쪽 === '꼬리') ? { ...c, 덧붙임: 추정토큰(뒷말) } : c)).map((c) => ({ ...c, 말조각: true }))];
    const { 것, 잘린무리 } = 빼기(모두, 남길);
    const 맥것 = 것.filter((c) => !c.말조각), 말것 = 것.filter((c) => c.말조각);
    const 새말 = [];
    말.forEach((x, k) => {
      const 머 = 말것.find((c) => c.말 === k && c.쪽 === '머리'), 꼬 = 말것.find((c) => c.말 === k && c.쪽 === '꼬리');
      if (!머 || 머.빠짐) return;
      새말.push(꼬 && 꼬.빠짐 ? { ...x, text: 머.글 + 뒷말 } : x);
    });
    const 글 = 글로(맥것, 잘린무리);
    const 산 = 맥것.filter((c) => !c.빠짐);
    return { 앞말: 새말, 맥락: 글, 남은문서: [...new Set(산.filter((c) => c.문서).map((c) => c.문서))], 남은조각: 산.filter((c) => c.조각 != null).map((c) => c.조각),
      추정: 고정 + 말토큰(새말) + 추정토큰(물음) + 추정토큰(글) + 1 };
  };
  const 꼭 = 조각들.filter((c) => (c.급 ?? 50) >= 급.센수).reduce((a, c) => a + 추정토큰(c.글) + 1, 0);
  const 잘림말 = '\n(질문이 길어 뒤를 잘랐다 — 잘린 부분은 못 봤다고 밝힐 것)';
  // 질문 하나가 정말 클 때만(센 수·표 머리·틀 몫을 빼고도 안 들어갈 때) 자른다.
  if (추정토큰(물음) > 한도 - 고정 - 꼭 - 4 * 말.length - 100) {
    for (let 번 = 0; 번 < 4 && 추정토큰(물음 + 잘림말) > 한도 - 고정 - 꼭 - 4 * 말.length - 40; 번++) {
      const 남 = 한도 - 고정 - 꼭 - 추정토큰(잘림말) - 4 * 말.length - 40;
      const 원 = 물음.endsWith(잘림말) ? 물음.slice(0, -잘림말.length) : 물음;
      물음 = 원.slice(0, Math.max(50, Math.floor(원.length * 남 / Math.max(1, 추정토큰(원))) - 20)) + 잘림말;
    }
  }
  // 덧붙는 글·어림 끝수로 조금 넘치면 그만큼 덜고 다시(두 번까지)
  let r = 풀기();
  for (let 번 = 0; 번 < 2 && r.추정 > 한도; 번++) r = 풀기((r.추정 - 한도) + 10);
  return { ...r, 질문: 물음, 처음, 줄였나: true };
}

export async function 답하기({ 질문, 히스토리 = [], 맥락 = '', 권한, fb, 표있다 = false, 화면들 = [], 고칠프로젝트 = [], 행위들 = [] }) {
  const 짓기 = (맥) => 지침(맥, 권한, 표있다, 화면들, 고칠프로젝트, 행위들);
  const 맞춤들 = new Map();                      // 한도마다 한 번만 맞춘다
  const 맞춤 = (한도) => {
    if (!맞춤들.has(한도)) 맞춤들.set(한도, 크기맞추기({ 질문, 앞말: 히스토리, 맥락, 짓기, 한도 }));
    return 맞춤들.get(한도);
  };
  const auth = await 토큰(fb);          // 게이트웨이는 회사 계정만 통과시킨다(v3.4부터 모든 제공자)
  // 실패를 **전부** 모은다. 마지막 것만 보여 주면 "cerebras 402" 한 줄만 남아서
  // 앞의 두 곳이 왜 안 됐는지(모델 폐기·지역 차단) 알 수 없다 — 부장님 첫 질문 때 실제로 그랬다.
  const 실패들 = [];
  // 안전망: 어림이 빗나가 그래도 413 이면 그 제공자의 한도를 25% 낮춰 **다시 맞춘다**(급 낮은 조각부터 더 빠진다).
  //   더 뺄 게 없어 보낼 글이 같으면 되풀이하지 않고 다음 제공자로 넘어간다(9/25 검토: 같은 몸을 세 번 보냈다).
  const 너무큼 = (m) => /\b413\b|too large|reduce your message|context length|maximum context/i.test(m);
  for (const p of 체인) {
    let 한도 = 제공자한도[p.id] || 큰한도, 앞서보낸 = null, 마지막오류 = null;
    for (let 번 = 0; 번 < 3; 번++) {
      const 이번 = 맞춤(한도);
      const sys = 짓기(이번.맥락);
      const 몸열쇠 = sys.length + '|' + 이번.앞말.length + '|' + 이번.질문.length + '|' + 이번.앞말.reduce((a, x) => a + String(x.text || '').length, 0);
      if (몸열쇠 === 앞서보낸) { 실패들.push((마지막오류 || p.id) + ' → 더 줄일 것이 없어 다음으로'); break; }
      앞서보낸 = 몸열쇠;
      try {
        const r = await 한번부르기(p, sys, 이번.앞말, 이번.질문, auth);
        // 무엇을 얼마나 보냈나를 남긴다 — **실제로 보낸 그 몸의** 어림(추정)과 제공자가 센 값(입력).
        //   둘이 벌어지면 계산식을 다시 맞출 때다.
        return { ...r, 남은문서: 이번.남은문서, 남은조각: 이번.남은조각, 토큰: { 추정: 이번.추정, 입력: r.입력토큰 ?? null, 줄임: 이번.줄였나 ? 이번.처음 : null, 다시: 번, 한도 } };
      } catch (e) {
        const msg = (e && e.name === 'AbortError') ? `${p.id}/${p.model}: ${제한초}초 초과` : ((e && e.message) || String(e));
        console.warn('[AI]', msg);
        if (번 < 2 && 너무큼(msg)) {
          // 실제로 보낸 크기에서 낮춘다. 고정 몫 + 400 아래로 내려가야 한다면 어림이 크게 빗나간 것 — 줄여 봐야
          //   질문만 잘린다. 줄이지 않고 다음 모델로 넘긴다.
          const 새한도 = Math.floor(Math.min(한도, 이번.추정) * 0.75);
          if (새한도 < 추정토큰(짓기('')) + 480) { 실패들.push(msg.slice(0, 200) + ' → 더 줄일 것이 없어 다음으로'); break; }
          한도 = 새한도; 마지막오류 = msg.slice(0, 200); continue;
        }
        실패들.push(msg.slice(0, 300));
        break;
      }
    }
  }
  throw new Error('AI가 답하지 못했습니다. 아래를 그대로 개발 담당에게 알려 주세요.\n' + 실패들.map((m) => '· ' + m).join('\n'));
}
