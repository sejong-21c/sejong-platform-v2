// 문서 조각내기 검사 — 브라우저 없이.  node test/rag-chunk.test.mjs
// 여기서 지키려는 것: 조각 하나만 봐도 "어느 문서 어느 장(章)인지" 알 수 있어야 한다.
// 그게 안 되면 AI 가 근거를 인용하지 못하고 "어딘가에 그렇게 적혀 있습니다" 수준으로 답한다.
import { 조각내기, 제목인가 } from '../tools/rag-chunk.mjs';

let 실패 = 0;
const 확인 = (이름, 참, 메모 = '') => {
  if (!참) 실패++;
  console.log(`${참 ? 'PASS' : 'FAIL'}  ${이름}${메모 ? '  — ' + 메모 : ''}`);
};
const nl = String.fromCharCode(10);   // 히어독이 역슬래시를 먹는 환경이라 줄바꿈은 이렇게 만든다

// ── 제목 판별 ──
확인('제목: 제5장', !!제목인가('제5장 부적합 관리'));
확인('제목: 제12조', !!제목인가('제12조 (목적)'));
확인('제목: 번호 5.2', !!제목인가('5.2 검사 및 시험'));
확인('제목: markdown', !!제목인가('## 부적합 처리'));
확인('제목: [부록 A]', !!제목인가('[부록 A]'));
확인('본문은 제목 아님', !제목인가('부적합품은 즉시 격리하고 식별표를 부착한다.'));
확인('긴 줄은 제목 아님', !제목인가('가'.repeat(90)));
확인('빈 줄은 제목 아님', !제목인가('   '));

// ── 조각내기 ──
const 문서 = [
  '제5장 부적합 관리',
  '5.1 식별',
  '부적합품은 발견 즉시 식별표를 부착하고 격리 구역으로 옮긴다.',
  '식별표에는 발견자, 발견일, 공정을 적는다.',
  '',
  '5.2 처리',
  '품질관리부장이 재작업·특채·폐기 중 하나를 결정한다.',
  '특채는 고객 승인을 받은 뒤에만 가능하다.',
  '',
  '제6장 시정조치',
  '반복되는 부적합은 시정조치 보고서(CAR)를 발행한다.',
].join(nl);

const 조각 = 조각내기(문서, '품질 매뉴얼 v3');
확인('조각이 만들어진다', 조각.length >= 2, `${조각.length}개`);
확인('모든 조각에 문서 이름이 붙는다', 조각.every((c) => c.startsWith('품질 매뉴얼 v3')), 조각[0].split(nl)[0]);
확인('장(章)과 절을 함께 적는다', 조각.some((c) => /제5장 부적합 관리 > 5\.1 식별/.test(c)), 조각[0].split(nl)[0]);
확인('다음 장은 앞 장을 물고 가지 않는다',
  조각.filter((c) => /제6장/.test(c)).every((c) => !/제5장/.test(c)),
  '제6장 조각에 제5장이 섞이면 잘못된 근거를 댄다');
확인('본문이 다 들어간다', 조각.join(' ').includes('고객 승인을 받은 뒤에만'));
확인('식별표 내용도 남는다', 조각.join(' ').includes('발견자, 발견일, 공정'));

// ── 길이 ──
const 긴본문 = '제1조 (목적)' + nl + '이 절차는 검사 업무를 규정한다. '.repeat(200);
const 긴조각 = 조각내기(긴본문, '검사 절차서', 900);
확인('긴 문서는 나뉜다', 긴조각.length > 1, `${긴조각.length}개`);
확인('조각이 최대치를 크게 넘지 않는다', 긴조각.every((c) => c.length <= 900 * 1.5), `최장 ${Math.max(...긴조각.map((c) => c.length))}자`);
확인('나뉜 조각에도 조문 제목이 붙는다', 긴조각.every((c) => c.includes('제1조 (목적)')));

// ── 가장자리 ──
확인('제목이 하나도 없는 글', 조각내기('그냥 줄글입니다. 두 문장입니다.', '메모').length === 1);
확인('빈 문서', 조각내기('', '빈 것').length === 1);
const 짧은 = 조각내기(['1. 가', '짧다.', '2. 나', '이것도 짧다.'].join(nl), 'T');
확인('토막 제목은 뭉쳐서 조각 수를 줄인다', 짧은.length <= 2, `${짧은.length}개`);

console.log(nl + (실패 ? '실패 ' + 실패 + '건' : '전부 통과'));
process.exit(실패 ? 1 : 0);
