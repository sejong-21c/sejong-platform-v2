/* AI 가 낸 「고치기 제안」을 글에서 떼어내는 부분만 검사한다 (2026-09-23, b83).
 *
 * 왜 이것만: 프로젝트·단락을 실제로 찾고 권한을 보고 쓰는 일은 전부 부모 앱(index.html)이 한다.
 *   여기 있는 실행뽑기()는 **모델이 뱉은 글자**를 다루는 유일한 자리다 — 모델은 시키지 않은 꼴로
 *   답하는 것이 정상이라, 이 함수가 헐거우면 엉뚱한 확인 카드가 뜨거나 JSON 이 말풍선에 그대로 보인다.
 *
 * 특히 지키는 것 둘:
 *   ① **덩이는 반드시 글에서 사라진다.** 남으면 사람이 중괄호를 읽게 된다.
 *   ② **의심스러우면 제안을 만들지 않는다.** 잘못 만든 카드는 누르면 진짜로 스케줄을 바꾼다 —
 *      못 알아들은 것은 그냥 답변으로 두는 편이 안전하다(사람이 다시 말하면 된다).
 */
import assert from 'node:assert';
import { 실행뽑기 } from '../modules/messenger/ai.js';

let n = 0;
const T = (why, fn) => { fn(); n++; };

// ── 제대로 된 것 ──────────────────────────────────────────────────────────
T('실행 덩이를 떼어내고 제안을 만든다', () => {
  const 글 = '삼성전기 3번 Tank 제작을 완료 처리하겠습니다.\n```실행\n{"도구":"스케줄","프로젝트":"SJ435-26","단락":"3","값":100}\n```';
  const r = 실행뽑기(글);
  assert.deepEqual(r.제안, { 도구: '스케줄', 프로젝트: 'SJ435-26', 단락: '3', 값: 100 });
  assert.equal(r.글, '삼성전기 3번 Tank 제작을 완료 처리하겠습니다.');
  assert.ok(!r.글.includes('{'), '덩이가 글에 남으면 안 된다');
});

T('```json 으로 싸도 받는다 — 모델이 자주 그렇게 쓴다', () => {
  const r = 실행뽑기('네.\n```json\n{"도구":"스케줄","프로젝트":"SJ428-25","단락":"이설장비 제작","값":70}\n```');
  assert.equal(r.제안.값, 70);
  assert.equal(r.제안.단락, '이설장비 제작');
  assert.equal(r.글, '네.');
});

T('울타리에 아무 말도 안 붙여도 받는다', () => {
  const r = 실행뽑기('```\n{"도구":"스케줄","프로젝트":"A","단락":"1","값":0}\n```');
  assert.equal(r.제안.값, 0, '0% 는 유효한 값이다 — 되돌리기에 쓴다');
});

T('0 과 100 은 경계 안이다', () => {
  for (const v of [0, 100]) {
    assert.ok(실행뽑기(`x\n\`\`\`실행\n{"도구":"스케줄","프로젝트":"A","단락":"1","값":${v}}\n\`\`\``).제안, `${v} 는 통과해야 한다`);
  }
});

// ── 제안을 만들면 안 되는 것 ──────────────────────────────────────────────
T('덩이가 없으면 글 그대로, 제안은 없다', () => {
  const r = 실행뽑기('부적합은 22건입니다.');
  assert.equal(r.제안, null);
  assert.equal(r.글, '부적합은 22건입니다.');
});

T('깨진 JSON 은 제안을 안 만든다 — 그래도 덩이는 치운다', () => {
  const r = 실행뽑기('네.\n```실행\n{"도구":"스케줄", 값:100,,}\n```');
  assert.equal(r.제안, null);
  assert.ok(!r.글.includes('도구'), '못 읽었어도 중괄호를 사람에게 보이면 안 된다');
});

T('모르는 도구는 거절한다 — 스케줄 말고는 아직 없다', () => {
  assert.equal(실행뽑기('x\n```실행\n{"도구":"NCR발행","프로젝트":"A","단락":"1","값":100}\n```').제안, null);
});

T('범위 밖 값은 거절한다 — 자르지 않는다', () => {
  // 자르면(clamp) 모델이 "150%" 라고 말한 것을 100 으로 **조용히** 바꿔 실행하게 된다.
  // 사람이 카드에서 100 을 보고 "내가 말한 대로네" 하고 누른다 — 그건 확인이 아니다.
  for (const v of [101, -1, 999]) {
    assert.equal(실행뽑기(`x\n\`\`\`실행\n{"도구":"스케줄","프로젝트":"A","단락":"1","값":${v}}\n\`\`\``).제안, null, `${v} 는 거절해야 한다`);
  }
});

T('값이 숫자가 아니면 거절한다', () => {
  for (const v of ['"완료"', 'null', '"100%"']) {
    assert.equal(실행뽑기(`x\n\`\`\`실행\n{"도구":"스케줄","프로젝트":"A","단락":"1","값":${v}}\n\`\`\``).제안, null, `${v} 는 거절해야 한다`);
  }
});

T('프로젝트나 단락이 비면 거절한다', () => {
  assert.equal(실행뽑기('x\n```실행\n{"도구":"스케줄","프로젝트":"","단락":"1","값":100}\n```').제안, null);
  assert.equal(실행뽑기('x\n```실행\n{"도구":"스케줄","프로젝트":"A","단락":"  ","값":100}\n```').제안, null);
  assert.equal(실행뽑기('x\n```실행\n{"도구":"스케줄","프로젝트":"A","값":100}\n```').제안, null);
});

T('빈 글·null 에도 안 터진다', () => {
  for (const x of ['', null, undefined]) assert.equal(실행뽑기(x).제안, null);
});

// ── 실수로 집지 않아야 할 것 ──────────────────────────────────────────────
T('보통 코드 블록을 제안으로 오해하지 않는다', () => {
  const r = 실행뽑기('SQL 은 이렇습니다.\n```sql\nSELECT count(*) FROM 표01\n```');
  assert.equal(r.제안, null);
  assert.ok(r.글.includes('SELECT'), 'sql 블록은 글에 남아야 한다');
});

T('덩이는 하나만 집는다 — 두 개 붙여 오면 앞의 것', () => {
  const r = 실행뽑기('a\n```실행\n{"도구":"스케줄","프로젝트":"A","단락":"1","값":100}\n```\nb\n```실행\n{"도구":"스케줄","프로젝트":"B","단락":"2","값":50}\n```');
  assert.equal(r.제안.프로젝트, 'A');
  // 두 번째는 글에 남는다 — 카드 하나만 뜨고, 남은 글자가 사람 눈에 띄어야 이상한 줄 안다.
  assert.ok(r.글.includes('"B"'), '집지 않은 덩이를 조용히 지우면 안 된다');
});

console.log(`ai-action 테스트 ${n}개 전체 통과 (실행뽑기)`);
