/* AI 가 낸 「고치기 제안」을 글에서 떼어내는 부분만 검사한다 (2026-09-23, b84).
 *
 * 왜 이것만: 대상을 실제로 찾고, 권한을 보고, 값을 따지고, 쓰는 일은 전부 부모 앱의
 *   행위 등록소(index.html 의 AI행위)가 한다. 여기 있는 실행뽑기()는 **모델이 뱉은 글자**를
 *   다루는 유일한 자리다 — 모델은 시키지 않은 꼴로 답하는 것이 정상이라, 이 함수가 헐거우면
 *   엉뚱한 확인 카드가 뜨거나 JSON 이 말풍선에 그대로 보인다.
 *
 * 이 함수가 지키는 것은 셋뿐이다:
 *   ① **덩이는 반드시 글에서 사라진다.** 남으면 사람이 중괄호를 읽게 된다.
 *   ② **할 수 있는 행위만 받는다.** 없는 행위로 카드를 띄우면 눌러 보고서야 안 된다는 걸 안다.
 *   ③ **칸 값은 글자나 수만.** null·true 를 Number() 에 넣으면 0 이 되는데 0 은 대개 유효한
 *      값이라 그대로 통과한다 — 값을 못 채운 것이 "0 으로 지워라" 로 읽힌다(실제로 잡은 버그).
 *   값의 범위(진척률 0~100 등)는 여기가 아니라 각 행위의 풀기() 가 본다. 행위마다 다르다.
 */
import assert from 'node:assert';
import { 실행뽑기 } from '../modules/messenger/ai.js';

const 있는행위 = ['스케줄진척', '프로젝트일정', '프로젝트상태', '업무완료', '업무배정', '업무등록'];
let n = 0;
const T = (why, fn) => { fn(); n++; };

// ── 제대로 된 것 ──────────────────────────────────────────────────────────
T('실행 덩이를 떼어내고 행위·인자로 가른다', () => {
  const 글 = '삼성전기 3번 Tank 제작을 완료 처리하겠습니다.\n```실행\n{"행위":"스케줄진척","프로젝트":"SJ435-26","단락":"3","값":100}\n```';
  const r = 실행뽑기(글, 있는행위);
  assert.deepEqual(r.제안, { 행위: '스케줄진척', 인자: { 프로젝트: 'SJ435-26', 단락: '3', 값: 100 } });
  assert.equal(r.글, '삼성전기 3번 Tank 제작을 완료 처리하겠습니다.');
  assert.ok(!r.글.includes('{'), '덩이가 글에 남으면 안 된다');
});

T('```json 으로 싸도, 울타리에 아무 말이 없어도 받는다', () => {
  assert.equal(실행뽑기('네.\n```json\n{"행위":"업무완료","업무":"도면 검토"}\n```', 있는행위).제안.인자.업무, '도면 검토');
  assert.equal(실행뽑기('```\n{"행위":"프로젝트일정","프로젝트":"A","마감일":"2026-04-30"}\n```', 있는행위).제안.행위, '프로젝트일정');
});

T('다섯 행위 모두 지나간다 — 등록소에 더해도 파서는 그대로', () => {
  for (const a of 있는행위) {
    assert.equal(실행뽑기(`x\n\`\`\`실행\n{"행위":"${a}","프로젝트":"A","업무":"B","값":50}\n\`\`\``, 있는행위).제안.행위, a);
  }
});

T('0 은 유효한 값이다 — 되돌릴 때 쓴다', () => {
  assert.equal(실행뽑기('x\n```실행\n{"행위":"스케줄진척","프로젝트":"A","단락":"1","값":0}\n```', 있는행위).제안.인자.값, 0);
});

T('목록을 안 주면 행위 이름을 안 따진다 — 부모가 어차피 거른다', () => {
  assert.equal(실행뽑기('x\n```실행\n{"행위":"뭔가","업무":"B"}\n```').제안.행위, '뭔가');
});

// ── 제안을 만들면 안 되는 것 ──────────────────────────────────────────────
T('덩이가 없으면 글 그대로, 제안은 없다', () => {
  const r = 실행뽑기('부적합은 22건입니다.', 있는행위);
  assert.equal(r.제안, null);
  assert.equal(r.글, '부적합은 22건입니다.');
});

T('깨진 JSON 은 제안을 안 만든다 — 그래도 덩이는 치운다', () => {
  const r = 실행뽑기('네.\n```실행\n{"행위":"스케줄진척", 값:100,,}\n```', 있는행위);
  assert.equal(r.제안, null);
  assert.ok(!r.글.includes('행위'), '못 읽었어도 중괄호를 사람에게 보이면 안 된다');
});

T('할 수 없는 행위는 거절한다', () => {
  // NCR 발행은 아직 등록소에 없다. 카드를 띄우면 눌러 보고서야 안 된다는 걸 알게 된다.
  assert.equal(실행뽑기('x\n```실행\n{"행위":"NCR발행","프로젝트":"A"}\n```', 있는행위).제안, null);
});

T('행위 이름이 없거나 비면 거절한다', () => {
  assert.equal(실행뽑기('x\n```실행\n{"프로젝트":"A","값":100}\n```', 있는행위).제안, null);
  assert.equal(실행뽑기('x\n```실행\n{"행위":"  ","프로젝트":"A"}\n```', 있는행위).제안, null);
});

T('**null·true·객체 칸은 버린다** — Number(null) 이 0 이라 값을 지운다', () => {
  // 실제로 잡은 버그다: 모델이 값을 못 채워 null 을 뱉으면 진척률을 0 으로 **지우는** 카드가 떴다.
  const r = 실행뽑기('x\n```실행\n{"행위":"스케줄진척","프로젝트":"A","단락":"1","값":null}\n```', 있는행위);
  assert.ok(!('값' in r.제안.인자), 'null 칸은 아예 없어야 한다 — 부모가 "안 준 것"으로 다룬다');
  for (const v of ['true', 'false', '{"a":1}', '[1,2]']) {
    const x = 실행뽑기(`y\n\`\`\`실행\n{"행위":"스케줄진척","프로젝트":"A","값":${v}}\n\`\`\``, 있는행위);
    assert.ok(!('값' in x.제안.인자), `${v} 칸은 버려야 한다`);
  }
});

T('빈 문자열 칸도 버린다 — 빈 값은 "안 준 것"이지 "지워라"가 아니다', () => {
  const r = 실행뽑기('x\n```실행\n{"행위":"업무배정","업무":"도면","담당자":"","마감일":"   "}\n```', 있는행위);
  assert.deepEqual(r.제안.인자, { 업무: '도면' });
});

T('칸이 하나도 안 남으면 거절한다', () => {
  assert.equal(실행뽑기('x\n```실행\n{"행위":"업무완료","업무":""}\n```', 있는행위).제안, null);
});

T('빈 글·null 에도 안 터진다', () => {
  for (const x of ['', null, undefined]) assert.equal(실행뽑기(x, 있는행위).제안, null);
});

// ── 실수로 집지 않아야 할 것 ──────────────────────────────────────────────
T('보통 코드 블록을 제안으로 오해하지 않는다', () => {
  const r = 실행뽑기('SQL 은 이렇습니다.\n```sql\nSELECT count(*) FROM 표01\n```', 있는행위);
  assert.equal(r.제안, null);
  assert.ok(r.글.includes('SELECT'), 'sql 블록은 글에 남아야 한다');
});

T('덩이는 하나만 집는다 — 두 개 붙여 오면 앞의 것', () => {
  const r = 실행뽑기('a\n```실행\n{"행위":"스케줄진척","프로젝트":"A","단락":"1","값":100}\n```\nb\n```실행\n{"행위":"스케줄진척","프로젝트":"B","단락":"2","값":50}\n```', 있는행위);
  assert.equal(r.제안.인자.프로젝트, 'A');
  // 두 번째는 글에 남는다 — 카드 하나만 뜨고, 남은 글자가 사람 눈에 띄어야 이상한 줄 안다.
  assert.ok(r.글.includes('"B"'), '집지 않은 덩이를 조용히 지우면 안 된다');
});

console.log(`ai-action 테스트 ${n}개 전체 통과 (실행뽑기)`);
