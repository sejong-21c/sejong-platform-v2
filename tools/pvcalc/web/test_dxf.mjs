// 견적용 외형도(pvcalc-dxf.js) 시험 — node web/test_dxf.mjs
//
// 왜: 외형도는 **치수가 틀려도 그림은 그럴듯하게 나온다**(제일 나쁜 종류). 경판 깊이 식, 전체 길이, 노즐 위치를 수로 못 박고,
//   DXF 파일이 CAD 에서 열리는 꼴인지(짝 맞는 코드/값 줄, 구역, EOF, 전부 아스키)를 본다.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const g = require("./pvcalc-dxf.js");

let 실패 = 0, 수 = 0;
const ok = (이름, 참, 더 = "") => { 수++; if (!참) { 실패++; console.log(`  [FAIL] ${이름}  ${더}`); } else console.log(`  [PASS] ${이름}`); };
const 가깝다 = (a, b, e = 1e-6) => Math.abs(a - b) <= e * Math.max(1, Math.abs(b));

console.log("── 경판 깊이 식");
ok("2:1 타원 h = D/4", 가깝다(g.경판깊이("ellip2", 2000), 500));
ok("일반 타원 h = D/(2k)", 가깝다(g.경판깊이("ellipG", 2000, { k: 2.5 }), 400));
ok("반구 h = D/2", 가깝다(g.경판깊이("hemi", 2000), 1000));
ok("원추 30° h = (D/2)/tan30", 가깝다(g.경판깊이("cone", 2000, { alpha: 30 }), 1000 / Math.tan(Math.PI / 6)));
// 접시형 L=D=2000, r=0.06L=120: h = 2000 − √(1880² − 880²)
ok("표준 접시(r=6%L) h = L − √((L−r)² − (D/2−r)²)", 가깝다(g.경판깊이("toriS", 2000, { L: 2000 }), 2000 - Math.sqrt(1880 ** 2 - 880 ** 2)));
ok("일반 접시 L·r 지정", 가깝다(g.경판깊이("toriG", 1500, { L: 1500, r: 150 }), 1500 - Math.sqrt(1350 ** 2 - 600 ** 2)));
let 막힘 = false; try { g.경판깊이("toriG", 1000, { L: 400, r: 100 }); } catch (e) { 막힘 = true; }
ok("접시형 L < D/2 는 거부(식이 안 선다)", 막힘);

console.log("── 노즐 바깥지름(ASME B36.10)");
ok('2" → 60.3 mm', 가깝다(g.노즐외경('2"'), 60.3));
ok("1-1/2 → 48.3", 가깝다(g.노즐외경("1-1/2"), 48.3));
ok("DN100 → 114.3", 가깝다(g.노즐외경("DN100"), 114.3));
ok("US 단위면 인치", 가깝다(g.노즐외경("4", "US"), 114.3 / 25.4));
ok("모르는 호칭은 null", g.노즐외경("7") === null);

console.log("── 모형 · 치수");
const 입 = {
  단위: "SI", 방향: "수평", D: 2000, t: 12, L: 6000,
  경판: { 형식: "ellip2", t: 14 },
  새들: { a: 1000, b: 250, 높이: 800 },
  노즐: [{ 마크: "N1", 호칭: '4"', 위치: 1500, 쪽: "위", 돌출: 200 }, { 마크: "N2", 호칭: '2"', 위치: 4500, 쪽: "아래" }, { 마크: "M1", 호칭: "20", 쪽: "오른경판" }],
  표제: { 프로젝트: "SJ435-26 삼성전기", 고객사: "삼성전기", 태그: "V-101", 품명: "Separator", 도면번호: "SJ435-26-ME-001", Rev: "0", 작성자: "김철우", 작성일: "2026-09-25", 기준: "ASME VIII-1" },
};
const m = g.외형도(입);
const 전장글 = m.글.find((x) => x.글.startsWith("전장 "));
ok("전장 = L + 2×(경판 깊이 + 경판 두께) — 2:1 타원이면 6000 + 2×(500+14) = 7028", 전장글 && 전장글.글 === "전장 7028", 전장글 && 전장글.글);
ok("T/T 치수 = L", m.글.some((x) => x.글 === "T/T 6000"));
ok("OD = D + 2t", m.글.some((x) => x.글 === "OD 2024"));
ok("새들 간격 = L − 2a", m.글.some((x) => x.글 === "4000"));
ok("노즐 위치 치수는 왼쪽 TL 부터", m.글.some((x) => x.글 === "N1 1500"));
ok("아래 노즐도 위치 치수(그림 밑)", m.글.some((x) => x.글 === "N2 4500" && x.p[1] < -1012));
ok('노즐 표기 "N1 (4")"', m.글.some((x) => x.글 === 'N1 (4")'));
const 셸선 = m.선.filter((s) => s.층 === "OUTLINE" && s.a[1] === s.b[1] && Math.abs(s.a[1]) === 1012);
ok("셸 윗·아랫선 y = ±(D/2+t)", 셸선.length === 2 && 셸선.every((s) => s.a[0] === 0 && s.b[0] === 6000));
const 오른 = m.폴리.find((p) => p.층 === "OUTLINE" && p.점.some(([x]) => x > 6000));
ok("오른쪽 타원 경판 꼭짓점 x = L + h + t", 오른 && 가깝다(Math.max(...오른.점.map(([x]) => x)), 6514));
let 밖 = false; try { g.외형도({ ...입, 노즐: [{ 마크: "N9", 호칭: "2", 위치: 7000, 쪽: "위" }] }); } catch (e) { 밖 = /0~L/.test(e.message); }
ok("노즐 위치가 셸 밖이면 거부", 밖);
const 표제 = m.글.filter((x) => x.층 === "TITLE").map((x) => x.글).join(" | ");
ok("표제란에 도면번호·Rev·작성자·기준", /SJ435-26-ME-001\s+Rev\.0/.test(표제) && 표제.includes("김철우") && 표제.includes("ASME VIII-1"), 표제);
ok("표제란에 '제작 도면 아님'", 표제.includes("제작 도면 아님"));
ok("축척이 표준 축척 중 하나", [1, 2, 2.5, 5, 10, 15, 20, 25, 30, 40, 50, 60, 75, 100, 150, 200].includes(m.축척), String(m.축척));
// 그림과 표제란이 안 겹친다 — 그림(표제란 빼고)의 밑이 표제란 윗변보다 위
const 틀 = m.폴리.filter((p) => p.층 === "TITLE");
const 표제위 = Math.max(...틀[1].점.map(([, y]) => y));
const 그림밑 = Math.min(...m.선.filter((s) => s.층 !== "TITLE").flatMap((s) => [s.a[1], s.b[1]]), ...m.폴리.filter((p) => p.층 !== "TITLE").flatMap((p) => p.점.map(([, y]) => y)));
ok("그림이 표제란과 겹치지 않는다", 그림밑 > 표제위, `${그림밑} vs ${표제위}`);

console.log("── 경판 형식마다 모형이 선다");
for (const 형식 of ["ellip2", "ellipG", "toriS", "toriG", "hemi", "cone", "flat"]) {
  let 됨 = true, 전장 = null;
  try {
    const mm = g.외형도({ ...입, 노즐: [], 경판: { 형식, t: 14, k: 2.5, L: 2000, r: 200, alpha: 30 } });
    전장 = Number((mm.글.find((x) => x.글.startsWith("전장 ")) || {}).글?.slice(3));
  } catch (e) { 됨 = false; }
  const 기대 = 6000 + 2 * (형식 === "flat" ? 14 : 형식 === "cone" ? 1000 / Math.tan(Math.PI / 6) + 14 / Math.sin(Math.PI / 6) : g.경판깊이(형식, 2000, { k: 2.5, L: 2000, r: 200, alpha: 30 }) + 14);
  ok(`${형식} 전장 ${Math.round(기대)}`, 됨 && Math.abs(전장 - 기대) <= 1, `${전장}`);
}
const 세움 = g.외형도({ ...입, 방향: "수직", 스커트: { 높이: 1500 } });
const 세움범위 = g.범위(세움);
ok("수직이면 세로로 길다", (세움범위.y1 - 세움범위.y0) > (세움범위.x1 - 세움범위.x0) * 0.8);
ok("수직 스커트 표기", 세움.글.some((x) => x.글.startsWith("스커트(개략) 1500")));

console.log("── 적대 검토(9/25)에서 잡힌 것");
const 던지나 = (f, 말) => { try { f(); return false; } catch (e) { return 말 ? 말.test(e.message) : true; } };
ok("접시형 L < D/2 는 그리기 전에 거부 — NaN DXF 가 안 나온다", 던지나(() => g.외형도({ ...입, 노즐: [], 경판: { 형식: "toriG", t: 14, L: 400, r: 100 } })));
ok("일반 접시형에 r 을 비우면 거부(뾰족한 경판을 말없이 그리지 않는다)", 던지나(() => g.외형도({ ...입, 노즐: [], 경판: { 형식: "toriG", t: 14, L: 2000, r: null } }), /너클 반경 r/));
ok("원추 α 90° 이상은 거부", 던지나(() => g.외형도({ ...입, 노즐: [], 경판: { 형식: "cone", t: 14, alpha: 95 } })));
ok("모르는 노즐 방향은 거부(왼쪽 경판에 말없이 그리지 않는다)", 던지나(() => g.외형도({ ...입, 노즐: [{ 마크: "N1", 호칭: "2", 위치: 1500, 쪽: "상단부" }] }), /방향/));
ok("비슷한 말은 맞춰 준다(오른쪽 경판·상부)", !던지나(() => g.외형도({ ...입, 노즐: [{ 마크: "A", 호칭: "2", 쪽: "오른쪽 경판" }, { 마크: "B", 호칭: "2", 위치: 100, 쪽: "상부" }] })));
ok("셸 노즐 위치가 비면 거부(x=0 에 말없이 그리지 않는다)", 던지나(() => g.외형도({ ...입, 노즐: [{ 마크: "N1", 호칭: "2", 위치: null, 쪽: "위" }] }), /위치/));
ok("새들 a ≥ L/2 는 거부(새들이 말없이 사라지지 않는다)", 던지나(() => g.외형도({ ...입, 노즐: [], 새들: { a: 3000, b: 250 } }), /0 < a < L\/2/));
const 새들점 = m.폴리.filter((p) => p.층 === "SUPPORT").flatMap((p) => p.점.map(([x]) => x));
ok("새들 옆모습은 축 방향으로 폭 b(+밑판)만 — 끝에서 본 폭으로 경판 밖까지 나가지 않는다", Math.min(...새들점) >= 1000 - 250 / 2 - 250 * 0.15 - 1e-6 && Math.max(...새들점) <= 5000 + 250 / 2 + 250 * 0.15 + 1e-6, `${Math.min(...새들점)}~${Math.max(...새들점)}`);
const 세운 = g.외형도({ ...입, 방향: "수직", 노즐: [], 스커트: { 높이: 1500 } });
const OD글 = 세운.글.find((x) => x.글.startsWith("OD "));
ok("수직이면 OD 치수를 위 경판 위에 가로로", OD글 && !OD글.세로 && OD글.p[1] > 6000, JSON.stringify(OD글 && OD글.p));
const 스커트 = 세운.폴리.find((p) => p.층 === "SUPPORT");
ok("스커트는 아래 TL(y=0)에서 바닥(−높이)까지", 스커트 && Math.max(...스커트.점.map(([, y]) => y)) === 0 && Math.min(...스커트.점.map(([, y]) => y)) === -1500);
ok("스커트가 아래 경판 깊이보다 짧으면 거부", 던지나(() => g.외형도({ ...입, 방향: "수직", 노즐: [], 스커트: { 높이: 300 } }), /스커트 높이/));
const 인치 = g.외형도({ ...입, 단위: "US", D: 78.74, t: 0.5, L: 236.2, 새들: { a: 39.4, b: 10, 높이: 31.5 }, 노즐: [] });
const 인치파일 = g.dxf(인치);
const 선형배율 = Number(인치파일.split("\r\n")[인치파일.split("\r\n").indexOf("$LTSCALE") + 2]);
ok("인치 도면은 LTSCALE = 축척/25.4 (mm 로 정의한 중심선이 실선으로 안 보이게)", Math.abs(선형배율 - 인치.축척 / 25.4) < 1e-6, String(선형배율));
ok("KS 호칭 50A = DN50 · 2B = NPS 2", 가깝다(g.노즐외경("50A"), 60.3) && 가깝다(g.노즐외경("2B"), 60.3) && 가깝다(g.노즐외경("1-1/2B"), 48.3));
const 접시 = g.외형도({ ...입, 노즐: [], 경판: { 형식: "toriS", t: 14, L: 2000 } });
const 접시범위 = g.범위({ ...접시, 글: [], 폴리: 접시.폴리.filter((p) => p.층 === "OUTLINE"), 선: 접시.선.filter((s) => s.층 === "OUTLINE") });   // 경판 윤곽만(새들은 뺀다)
ok("호 범위는 그린 부분만 — 크라운 반경 원 전체로 부풀지 않는다", 접시범위.y1 < 1100 && 접시범위.y0 > -1100, `${접시범위.y0}~${접시범위.y1}`);

console.log("── DXF 파일");
const 파일 = g.dxf(m);
const 줄 = 파일.replace(/\r\n$/, "").split("\r\n");
ok("줄 수가 짝수(코드·값 짝)", 줄.length % 2 === 0, String(줄.length));
ok("홀수 줄은 전부 정수 그룹 코드", 줄.every((v, i) => i % 2 || /^\s*-?\d+$/.test(v)));
ok("R12(AC1009) · 한국어 코드페이지", 파일.includes("$ACADVER\r\n1\r\nAC1009") && 파일.includes("ANSI_949"));
ok("구역 HEADER·TABLES·ENTITIES 와 끝 EOF", ["HEADER", "TABLES", "ENTITIES"].every((s) => 파일.includes("2\r\n" + s)) && 줄.slice(-2).join("|") === "0|EOF");
ok("파일 전체가 아스키(한글은 \\U+XXXX)", /^[\x00-\x7f]*$/.test(파일));
ok("한글 표기 보존(\\U+ 로)", 파일.includes(g.아스키로("견적·사전검토용")) && g.아스키로("견") === "\\U+ACAC");
const 개수 = (종) => 줄.filter((v, i) => i % 2 === 1 && 줄[i - 1] === "0" && v === 종).length;
ok("개체 수가 모형과 같다", 개수("LINE") === m.선.length && 개수("ARC") === m.호.length && 개수("POLYLINE") === m.폴리.length && 개수("TEXT") === m.글.length && 개수("SEQEND") === m.폴리.length);
ok("쓰인 층은 전부 LAYER 표에 있다", (() => { const 표 = new Set(["0", "OUTLINE", "CENTER", "DIM", "NOZZLE", "SUPPORT", "TEXT", "TITLE"]); return 줄.every((v, i) => !(i % 2 === 1 && 줄[i - 1] === "8") || 표.has(v)); })());
ok("SVG 미리보기", /^<svg[\s\S]*<\/svg>$/.test(g.svg(m)) && g.svg(m).includes("T/T 6000"));

console.log(`\n${수} checks, ${실패} failure(s)`);
process.exit(실패 ? 1 : 0);
